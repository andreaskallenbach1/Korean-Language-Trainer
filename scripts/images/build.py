"""Turns the downloaded Unsplash thumbnails (scripts/images/raw) into
src/data/images.ts with embedded data URIs, so the app needs no image host.

Usage: python3 scripts/images/build.py   (after downloading, see README)
"""
import base64, csv, json, pathlib, subprocess

root = pathlib.Path(__file__).parent
out = {}
with open(root / "manifest.tsv", encoding="utf-8") as f:
    for ko, asset_id, photo, author in csv.reader(f, delimiter="\t"):
        src = root / "raw" / f"{asset_id}.jpg"
        webp = subprocess.run(
            ["convert", str(src), "-resize", "200x200^", "-gravity", "center", "-extent", "200x200", "-quality", "62", "webp:-"],
            check=True, capture_output=True,
        ).stdout
        out[ko] = {
            "src": "data:image/webp;base64," + base64.b64encode(webp).decode(),
            "author": author,
            "link": f"https://unsplash.com/photos/{asset_id}",
        }

ts = (
    "// Generated by scripts/images/build.py from Unsplash photos (Unsplash License).\n"
    "// Do not edit by hand.\n\n"
    "export interface WordImage {\n  src: string;\n  author: string;\n  link: string;\n}\n\n"
    f"export const WORD_IMAGES: Record<string, WordImage> = {json.dumps(out, ensure_ascii=False, indent=1)};\n"
)
(root.parent.parent / "src" / "data" / "images.ts").write_text(ts, encoding="utf-8")
print(len(out), "images,", len(ts) // 1024, "KB")
